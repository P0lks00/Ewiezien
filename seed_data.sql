DO $$
DECLARE
    rec RECORD;
    seq_name TEXT;
    max_id BIGINT;
BEGIN
    FOR rec IN
        SELECT * FROM (VALUES
            ('cele', 'id_celi'),
            ('personel', 'id_funkcjonariusza'),
            ('wiezniowie', 'id_wieznia'),
            ('wyroki', 'id_wyroku'),
            ('przydzialy_cel', 'id_przydzialu'),
            ('widzenia', 'id_widzenia'),
            ('incydenty', 'id_incydentu')
        ) AS t(tbl, col)
    LOOP
        seq_name := pg_get_serial_sequence(rec.tbl, rec.col);
        IF seq_name IS NOT NULL THEN
            EXECUTE format('SELECT COALESCE(MAX(%I), 1) FROM %I', rec.col, rec.tbl)
                INTO max_id;
            PERFORM setval(seq_name, max_id, true);
        END IF;
    END LOOP;
END $$;

